const form = document.getElementById("rsvpForm");
const confirmBox = document.getElementById("rsvpConfirm");
const confirmText = document.getElementById("rsvpConfirmText");


form.addEventListener("submit", async (event) => {

  event.preventDefault();

  const name = document
    .getElementById("fullname")
    .value
    .trim();

  const attending = document
    .getElementById("attending")
    .value;

  const submitButton = form.querySelector(
    'button[type="submit"]'
  );

  submitButton.disabled = true;


  try {

    const response = await fetch(form.action, {
      method: "POST",
      body: new FormData(form),
      headers: {
        Accept: "application/json"
      }
    });


    if (!response.ok) {
      throw new Error("Formspree error");
    }


    form.style.display = "none";
    confirmBox.style.display = "block";


    const template =
      attending === "oui"
        ? getTranslation("rsvpYes")
        : getTranslation("rsvpNo");


    confirmText.textContent =
      template.replace("{name}", name);


  } catch (error) {

    console.error(error);

    alert(getTranslation("rsvpError"));

    submitButton.disabled = false;
  }

});


